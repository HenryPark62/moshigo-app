BOTH_HIGH = {"umami": "진한 감칠맛", "soft": "부드러운 식감", "sweet": "달큰한 맛", "oily": "고소하고 기름진 맛", "aroma": "향이 진한", "salty": "짭짤한 간", "spicy": "매콤한 맛", "sour": "새콤한 맛"}
LEVELS = [(0.78, "아주 닮았어요", 3), (0.64, "꽤 닮았어요", 2), (0.50, "조금 닮았어요", 1)]


def _taste_sim(a, b):
    d = math.sqrt(sum(w * (x - y) ** 2 for x, y, w in zip(a, b, WEIGHT)))
    return max(0.0, 1 - d / 0.85)


def similarity(item, food):
    """item: 메뉴 {taste[8], ingredient, cooking, aroma_kw, texture_kw}. 0~1과 닮은 점."""
    _, vec, ing, cook, aroma, texture = WORLD[food]
    s = _taste_sim(item["taste"], vec)
    shared = []
    same_ing = item.get("ingredient") == ing
    if same_ing:
        s += 0.18
        shared.append(ing)
    if item.get("cooking") and item["cooking"] == cook:
        s += 0.08
        shared.append(cook)
    for i, axis in enumerate(AXES):
        if item["taste"][i] >= 0.6 and vec[i] >= 0.6 and len(shared) < 4:
            shared.append(BOTH_HIGH[axis])
    if not same_ing:  # 주재료가 다르면 '조금 닮았어요'까지만
        s = min(s - 0.06, 0.62)
        if item.get("cooking") != cook:  # 주재료도 조리법도 다르면 맛 수치만 비슷한 것이라 닮은꼴로 치지 않는다
            s = min(s, 0.45)
    return min(1.0, s), shared


def difference(item, food):
    """닮았지만 무엇이 다른지 한 문장으로."""
    _, vec, _, _, aroma, _ = WORLD[food]
    parts = []
    new_aroma = [a for a in item.get("aroma_kw") or [] if a not in aroma]
    if new_aroma:
        parts.append(f"{new_aroma[0]}이 나고")
    gaps = sorted(((item["taste"][i] - vec[i], ax) for i, ax in enumerate(AXES) if ax in AXIS_WORD), key=lambda g: -abs(g[0]))
    for gap, ax in gaps[:2]:
        if abs(gap) >= 0.2:
            parts.append(("조금 " if abs(gap) < 0.35 else "") + AXIS_WORD[ax][0 if gap > 0 else 1])
    if not parts:
        return "거의 같은 맛이에요."
    text = ", ".join(parts)
    if text.endswith("나고"):
        text = text[:-2] + "나요"
    return "다른 점: " + text + "."


def best_match(item, favorites):
    """좋아하는 음식 가운데 가장 닮은 것. 닮지 않았으면 None."""
    best = None
    for f in favorites:
        if f not in WORLD:
            continue
        s, shared = similarity(item, f)
        if best is None or s > best["score"]:
            best = {"food": f, "score": round(s, 2), "shared": shared}
    if not best:
        return None
    for th, word, bars in LEVELS:
        if best["score"] >= th:
            return {**best, "level": word, "bars": bars, "difference": difference(item, best["food"])}
    return None


def taste_map(item, matches):
    """맛 지도: 메뉴와 각자 기준 음식을 두 축(진한 맛, 부드러움)에 찍는다."""
    def xy(v):  # x: 담백 -> 진함 (짠맛, 감칠맛, 기름짐), y: 씹는 맛 -> 부드러움
        return round((v[0] + v[4] + v[6]) / 3, 3), round(v[7], 3)
    pts = [{"name": "이 메뉴", "kind": "menu", "x": xy(item["taste"])[0], "y": xy(item["taste"])[1]}]
    for m in matches:
        if not m or m["food"] not in WORLD:
            continue
        same = next((p for p in pts if p["name"] == m["food"]), None)
        if same:
            same["who"] += [w for w in m.get("who", []) if w not in same["who"]]
            continue
        x, y = xy(WORLD[m["food"]][1])
        pts.append({"name": m["food"], "kind": "food", "x": x, "y": y, "who": list(m.get("who", []))})
    return pts
